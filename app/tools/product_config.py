"""Versioned experiment contract. Presets are controlled experiments, not weather forecasts."""
import math, struct, hashlib, json
import channel_config
from functools import lru_cache
from pathlib import Path

FIELDS=('schema','environment','weather','formation','spacing_m','altitude_m','center_x_m','center_y_m','speed_mmps','heading_deg','reference_snr_cdb','faults','jitter_percent','carrier_mhz','external_node','reserved')
ENVIRONMENTS=('demo','open_field','rural','suburb','city','mountain','hills','plateau')
WEATHERS=('clear','fog','light_rain','rain','heavy_rain','light_snow','snow','heavy_snow')
FORMATIONS=('legacy_x','line','column','v','triangle','trapezoid','diamond','grid','circle')
ENV_NAMES=('三环境连续演示','旷野','乡村','郊区','城市','山地','丘陵','高原')
WEATHER_NAMES=('晴天','雾','小雨','中雨','大雨','小雪','中雪','大雪')
FORMATION_NAMES=('X形','横列','纵列','V形','三角形','梯形','菱形','方阵','环形')
DEFAULT=dict(zip(FIELDS,(1,0,0,0,300,400,5000,5000,12000,0,3400,0,100,2400,0,0)))

@lru_cache(maxsize=9)
def formation_points(shape):
    if shape==0:p=[(sx*r,sy*r) for sx,sy in ((-1,-1),(-1,1),(1,1),(1,-1)) for r in (4,3,2,1)]
    elif shape==1:p=[(i-7.5,0) for i in range(16)]
    elif shape==2:p=[(0,i-7.5) for i in range(16)]
    elif shape==3:p=[((i//2+.5)*(1 if i%2 else -1),i//2) for i in range(16)]
    elif shape==4:p=[(j-(row-1)/2,-row*math.sqrt(3)/2) for row in range(1,6) for j in range(row)]+[(0,1)]
    elif shape==5:p=[(j-(row+2)/2,-row) for row in range(4) for j in range(row+3)][:16]
    elif shape==6:p=[(x+y,x-y) for x in (-1.5,-.5,.5,1.5) for y in (-1.5,-.5,.5,1.5)]
    elif shape==7:p=[(x,y) for x in (-1.5,-.5,.5,1.5) for y in (-1.5,-.5,.5,1.5)]
    elif shape==8:p=[(math.cos(i*math.tau/16),math.sin(i*math.tau/16)) for i in range(16)]
    else:raise ValueError('未知编队')
    distance=min(math.dist(a,b) for i,a in enumerate(p) for b in p[i+1:])
    mx=sum(x for x,y in p)/16;my=sum(y for x,y in p)/16
    return [((x-mx)/distance,(y-my)/distance) for x,y in p]

def validate(data):
    if not isinstance(data,dict) or set(data)-set(FIELDS)-{'channel'}:raise ValueError('配置字段未知')
    c={**DEFAULT,**{k:v for k,v in data.items() if k!='channel'}}
    for k,v in c.items():
        if isinstance(v,bool) or not isinstance(v,int):raise ValueError(k+' 必须为整数')
    limits={'schema':(1,1),'environment':(0,7),'weather':(0,7),'formation':(0,8),'spacing_m':(150,1100),'altitude_m':(100,800),'center_x_m':(500,9500),'center_y_m':(500,9500),'speed_mmps':(0,20000),'heading_deg':(0,359),'reference_snr_cdb':(0,4500),'faults':(0,1),'jitter_percent':(0,200),'carrier_mhz':(200,6000),'external_node':(0,16),'reserved':(0,64)}
    for k,(a,b) in limits.items():
        if not a<=c[k]<=b:raise ValueError(f'{k} 范围为 {a}–{b}')
    if c['external_node'] in (9,13):raise ValueError('9、13 为 FPGA 硬件端点，不能同时配置外部注入')
    radius=max(math.hypot(x,y) for x,y in formation_points(c['formation']))*c['spacing_m']+400
    if radius>min(c['center_x_m'],10000-c['center_x_m'],c['center_y_m'],10000-c['center_y_m']):
        raise ValueError('编队、运动余量或间距超出 10 km × 10 km 边界')
    if 'channel' in data:
        c['channel']=channel_config.validate(data['channel'])
        if c['channel']['mode']==1 and 2<=c['weather']<=4 and c['carrier_mhz']<1000:
            raise ValueError('标准雨衰模型适用频率从 1 GHz 起；请提高载频或选自主信道模式')
        minimum=math.ceil((37,15,28,37,21,233,125,118)[c['environment']]+.024*c['spacing_m']+1)
        if c['channel']['mode']==1 and c['channel']['reserved0'] and c['altitude_m']<minimum:
            raise ValueError(f'启用地形传播时，本区域飞行高度至少 {minimum} m，保证整个轨迹不进入地面；当前为 {c["altitude_m"]} m')
    return c

def encode(data):return struct.pack('<16i',*(validate(data)[k] for k in FIELDS))
def config_hash(data):
    # Preserve historical scene-only digests. New experiments bind both blocks.
    c=validate(data);raw=encode(c)
    if 'channel' in c:raw+=b'CHANNEL1'+channel_config.encode(c['channel'])
    return hashlib.sha256(raw).hexdigest()
def wire_id(data):
    n=2166136261
    for b in encode(data):n=((n^b)*16777619)&0xffffffff
    return n

def catalog():
    rows=lambda ids,names:[dict(id=i,key=key,name=name) for i,(key,name) in enumerate(zip(ids,names))]
    return dict(schema=1,defaults=DEFAULT,environment=rows(ENVIRONMENTS,ENV_NAMES),weather=rows(WEATHERS,WEATHER_NAMES),formation=rows(FORMATIONS,FORMATION_NAMES),
                channel_defaults=channel_config.DEFAULT,
                scope='1–8 抽头数字基带实验；支持场景系数与自主系数。雨衰使用 P.838，其余地形/天气为公开的受控参数假设。',
                severe_weather=[4,6,7],external_node_scope='接口开发与单板注入；第二块板接入尚未验证')

